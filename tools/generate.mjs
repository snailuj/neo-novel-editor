// The generator as a library: build.mjs calls it, gen.mjs wraps it as a command.
// Output is byte-stable: sorted walk, fixed banner, no timestamps, LF endings.
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { walkSchemas } from './schemas.mjs';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const banner = 'Generated by tools/gen.mjs from schemas/. Do not edit; run `npm run gen`.';

const lf = (text) => text.replace(/\r\n?/g, '\n');

async function typeFiles(schemas, schemasDir) {
  const files = new Map();
  for (const { file, name, schema } of schemas) {
    const text = await compile(structuredClone(schema), name, {
      bannerComment: `/* ${banner} */`,
      cwd: schemasDir + path.sep,
      additionalProperties: false,
      // -1 keeps maxItems as a note; the default expands it into one tuple per length.
      maxItems: -1,
    });
    files.set(file.replace(/\.json$/, '.d.ts'), lf(text));
  }
  return files;
}

function validatorFiles(schemas) {
  const ajv = new Ajv({ strict: true, allErrors: true, code: { source: true } });
  const exports = {};
  for (const { file, name, schema } of schemas) {
    ajv.addSchema(structuredClone(schema), file);
    exports[`validate${name}`] = file;
  }
  const code = lf(standaloneCode(ajv, exports));

  const imports = schemas.map(({ file, name }) => {
    const module = `./${file.replace(/\.json$/, '.js')}`;
    return `import type { ${name} } from '${module}';`;
  });
  const declarations = schemas.map(
    ({ name }) => `export const validate${name}: Validator<${name}>;`,
  );
  const declaration = [
    `// ${banner}`,
    "import type { ErrorObject } from 'ajv';",
    ...imports,
    '',
    'export interface Validator<T> {',
    '  (data: unknown): data is T;',
    '  errors?: ErrorObject[] | null;',
    '}',
    '',
    ...declarations,
    '',
  ].join('\n');

  return new Map([
    ['validators.cjs', `// ${banner}\n${code}`],
    ['validators.d.cts', declaration],
  ]);
}

async function existing(dir, prefix = '') {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return [];
    throw error;
  }
  const found = [];
  for (const entry of entries) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) found.push(...await existing(path.join(dir, entry.name), rel));
    else found.push(rel);
  }
  return found;
}

async function read(file) {
  try {
    return await readFile(file, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

// Writes (or, with `check`, compares) every generated file under <root>/src/generated.
// Returns {schemas, differing}: the walked schemas, and the generated-directory paths that
// were out of date, missing or stale. A file is written only if its content changed, so a
// build on a clean tree touches nothing.
export async function generate({ root = repoRoot, check = false } = {}) {
  const schemasDir = path.join(root, 'schemas');
  const outDir = path.join(root, 'src', 'generated');
  const schemas = await walkSchemas(schemasDir);
  const wanted = new Map([...await typeFiles(schemas, schemasDir), ...validatorFiles(schemas)]);

  const differing = [];
  for (const [rel, content] of wanted) {
    const target = path.join(outDir, rel);
    if (await read(target) === content) continue;
    differing.push(path.posix.join('src/generated', rel));
    if (!check) {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
    }
  }
  for (const rel of await existing(outDir)) {
    if (wanted.has(rel)) continue;
    differing.push(path.posix.join('src/generated', rel));
    if (!check) await rm(path.join(outDir, rel));
  }
  return { schemas, differing };
}
